export const WATCHED_VIDEOS_KEY = 'it_study_hub_watched_videos_v1';

export function getWatchedVideoIds(): string[] {
  try {
    const raw = localStorage.getItem(WATCHED_VIDEOS_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

export function saveWatchedVideoIds(ids: string[]): void {
  try {
    localStorage.setItem(WATCHED_VIDEOS_KEY, JSON.stringify(ids));
  } catch {
    // ignore storage errors
  }
}
